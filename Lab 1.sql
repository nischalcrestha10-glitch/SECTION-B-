#2 SALARY STATISTICS OF ACCOUNT DEPARTMENT 
#SUM.MAX,MIN,AVG,FOR DEPARTMENT ADMINISTRATION
select sum(E.SALARY) AS TOTAL,
MAX(E.SALARY) as max,
MIN(E.SALARY) as min,
avg(E.SALARY) as average
FROM EMPLOYEE E 
join DEPARTMENT D on E.DNO = D.DNUMBER 
where D.DNAME='Hr';


