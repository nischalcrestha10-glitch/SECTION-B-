-- Create Database
CREATE DATABASE COMPANYDB;

-- Use Database
USE COMPANYDB;

-- Create DEPARTMENT Table
CREATE TABLE DEPARTMENT (
    DNAME VARCHAR(20),
    DNUMBER INT PRIMARY KEY,
    MGRSSN VARCHAR(15),
    MGRSTARTDATE DATE
);

-- Create EMPLOYEE Table
CREATE TABLE EMPLOYEE (
    FNAME VARCHAR(20),
    MINIT CHAR(1),
    LNAME VARCHAR(15),
    SSN VARCHAR(15) PRIMARY KEY,
    BDATE DATE,
    ADDRESS VARCHAR(100),
    SEX CHAR(1),
    SALARY INT,
    SUPERSSN VARCHAR(15),
    DNO INT,
    FOREIGN KEY (DNO) REFERENCES DEPARTMENT(DNUMBER)
);

